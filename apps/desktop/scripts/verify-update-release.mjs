import assert from "node:assert/strict";
import {createRequire} from "node:module";
import {createHash} from "node:crypto";
import {readFile,writeFile,stat} from "node:fs/promises";
import path from "node:path";
import {fileURLToPath} from "node:url";
const require=createRequire(import.meta.url);
const {load}=createRequire(require.resolve("electron-updater"))("js-yaml");
const {extractFile,statFile}=createRequire(createRequire(require.resolve("electron-builder")).resolve("app-builder-lib"))("@electron/asar");
const desktop=path.resolve(path.dirname(fileURLToPath(import.meta.url)),"..");
const pkg=JSON.parse(await readFile(path.join(desktop,"package.json"),"utf8"));
const directory=path.resolve(process.argv[2]??path.join(desktop,"dist"));
const installer="AMP.Setup."+pkg.version+".exe";
const latest=load(await readFile(path.join(directory,"latest.yml"),"utf8"));
assert.equal(latest.version,pkg.version);assert.equal(latest.path,installer);
assert.equal(latest.files.length,1);assert.equal(latest.files[0].url,installer);
const bytes=await readFile(path.join(directory,installer));
const sha512=createHash("sha512").update(bytes).digest("base64");
assert.equal(latest.sha512,sha512);assert.equal(latest.files[0].sha512,sha512);
assert.equal(latest.files[0].size,bytes.length);
assert.ok((await stat(path.join(directory,installer+".blockmap"))).size>0);
const resources=path.join(directory,"win-unpacked","resources");
const feed=load(await readFile(path.join(resources,"app-update.yml"),"utf8"));
assert.equal(feed.provider,"github");assert.equal(feed.owner,"tbhtho");assert.equal(feed.repo,"Advanced-Music-Player");assert.notEqual(feed.private,true);
assert.equal(feed.token,undefined);assert.equal(feed.requestHeaders,undefined);
const archive=path.join(resources,"app.asar");
const packaged=JSON.parse(extractFile(archive,"package.json").toString("utf8"));
assert.equal(packaged.version,pkg.version);assert.equal(packaged.name,pkg.name);assert.equal(pkg.build.appId,"com.amp.desktop");
assert.ok(packaged.dependencies["electron-updater"]);
assert.ok(statFile(archive,path.join("node_modules","electron-updater","package.json")));
const bundled=JSON.parse(extractFile(archive,path.join("dist-electron","bundled-desktop-config.json")).toString("utf8"));
assert.ok(bundled.SPOTIFY_CLIENT_ID);
assert.deepEqual(Object.keys(bundled).filter(key=>/secret|token|pass/i.test(key)),[]);
const main=extractFile(archive,path.join("dist-electron","main.js")).toString("utf8");
for(const channel of ["update-get-state","update-check","update-download","update-install"])assert.ok(main.includes("spot-cloud:"+channel));
const assets=[installer,installer+".blockmap","latest.yml"];
const sums=[];
for(const name of assets)sums.push(createHash("sha256").update(await readFile(path.join(directory,name))).digest("hex")+"  "+name);
await writeFile(path.join(directory,"SHA256SUMS.txt"),sums.join("\n")+"\n","utf8");
console.log(JSON.stringify({version:pkg.version,installer,installerBytes:bytes.length,metadataSHA512Verified:true,blockmapPresent:true,packagedUpdaterPresent:true,publicTokenFreeFeed:true,publisherSigningConfigured:Boolean(feed.publisherName),assets:[...assets,"SHA256SUMS.txt"]}));
